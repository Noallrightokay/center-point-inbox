#!/usr/bin/env bash
# Assemble the desktop app's web assets from the one interface RATA has.
#
# There is deliberately no second copy of app.html in this repository. It is
# 250KB and two copies of it diverge within a month, with the desktop one being
# the copy nobody remembers to update. So it is taken from rata-next/public at
# build time, and the only differences are applied here, loudly.
#
#   ./sync-ui.sh [folder]      (default: ui/, which Tauri compiles in)
#
# RATA_DISTRIBUTION says which build this is (below).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
src="$here/../../rata-next/public"
out="${1:-$here/ui}"

[ -d "$src" ] || { echo "no interface at $src" >&2; exit 1; }

# Which build this is. 'direct', the default, is the installers on the
# releases page: they update themselves and link to mailrata.org's prices and
# billing. 'store' is for Apple's and Google's stores, which update the app
# themselves and allow nothing in it that leads to a purchase anywhere else.
# The page reads it from config.js (`distribution`), never from the user
# agent. Unset means direct; anything else, an empty value included, stops
# here, because a store build that quietly came out direct would show its buy
# links to the store's reviewer.
dist="${RATA_DISTRIBUTION-direct}"
case "$dist" in
  direct|store) ;;
  *) echo "RATA_DISTRIBUTION must be direct or store, not '$dist'" >&2; exit 1 ;;
esac

# A folder named on the command line is emptied first, so it must be new,
# empty, or an earlier build of this script: nothing at its top but the names
# written here (and the .DS_Store a Mac's Finder leaves), with this script's
# own config.js among them, which is written first so that a build cut short
# still counts. Never a folder of someone's files, or "." given by mistake.
# ui/ is this script's own, and is emptied as it always was.
if [ -n "${1:-}" ] && { [ -e "$out" ] || [ -L "$out" ]; }; then
  if [ ! -d "$out" ] || [ -L "$out" ]; then
    echo "$out is not a folder this script assembled; give a new or empty folder" >&2
    exit 1
  fi
  strangers="$(
    shopt -s nullglob dotglob
    for e in "$out"/*; do
      n="${e##*/}"
      case "$n" in
        fonts|icons|vendor) [ -d "$e" ] && [ ! -L "$e" ] && continue ;;
        app.html|auth.html|index.html|bridge.js|bridge.css|config.js|manifest.json|.DS_Store) [ -f "$e" ] && [ ! -L "$e" ] && continue ;;
      esac
      printf '%s ' "$n"
    done
  )"
  if [ -n "$strangers" ]; then
    echo "$out is not a folder this script assembled (it holds ${strangers% }); give a new or empty folder" >&2
    exit 1
  fi
  held="$(shopt -s nullglob dotglob; for e in "$out"/*; do [ "${e##*/}" = .DS_Store ] || printf x; done)"
  if [ -n "$held" ] && ! head -n 1 "$out/config.js" 2>/dev/null | grep -q '^/\* Generated by sync-ui\.sh'; then
    echo "$out is not a folder this script assembled (it has no config.js of this script's); give a new or empty folder" >&2
    exit 1
  fi
fi

rm -rf "$out"
mkdir -p "$out"

# The device build has no Supabase and no server, which is exactly the state
# app.html already handles: it falls back to on-device accounts. The payment
# links still point at the website, because that is where buying happens.
#
# stripePortal is where Settings' "Switch plan in billing portal" and "Open
# billing portal" go (renderPlan), in the browser through open_link. The
# Stripe portal's own login link is a deploy setting (STRIPE_PORTAL) that
# this build does not have, so it goes to the page that does: RATA's page at
# mailrata.org/app, whose Settings shows the portal once signed in (signed
# out, auth.html brings the customer back there). Not /account, which shows
# a live subscriber only the licence key and has no way to the portal.
#
# `pages` are the other places on the web this build sends people, read by
# app.html and bridge.js, which hold none of these addresses themselves (the
# harness checks), so a store build cannot carry them: `account`, where the
# mailrata.org account is managed and deleted (Settings, Delete account);
# `licence`, where the licence key is found (the licence box); `releases`,
# where the installers are (the update bar, when an update fails). Help,
# Report a bug, Privacy and Terms are the website's own unless named here.
#
# The store build sells nothing and links to nothing that does: no payment
# links, no billing portal, no releases, and the store-safe pages under
# mailrata.org/in-app/, which have no way to prices, the licence page, the
# sign-in, Stripe or the releases (rata-next/lib/in-app.js).
if [ "$dist" = store ]; then
cat > "$out/config.js" <<'JS'
/* Generated by sync-ui.sh — do not edit. The desktop build has no cloud
   backend by design; app.html already treats that as "device account".
   This is the store build (RATA_DISTRIBUTION=store). */
window.RATA_CONFIG = {
  supabaseUrl: '',
  supabaseKey: '',
  stripeBase: '',
  stripePro: '',
  stripePortal: '',
  desktop: true,
  distribution: 'store',
  pages: {
    help: 'https://mailrata.org/in-app/help',
    bug: 'https://mailrata.org/in-app/help#report',
    privacy: 'https://mailrata.org/in-app/privacy',
    terms: 'https://mailrata.org/in-app/terms',
    account: 'https://mailrata.org/in-app/delete-account',
  },
};
JS
else
cat > "$out/config.js" <<'JS'
/* Generated by sync-ui.sh — do not edit. The desktop build has no cloud
   backend by design; app.html already treats that as "device account". */
window.RATA_CONFIG = {
  supabaseUrl: '',
  supabaseKey: '',
  stripeBase: 'https://mailrata.org/#pricing',
  stripePro: 'https://mailrata.org/#pricing',
  stripePortal: 'https://mailrata.org/app',
  desktop: true,
  distribution: 'direct',
  pages: {
    account: 'https://mailrata.org/app',
    licence: 'https://mailrata.org/account',
    releases: 'https://github.com/Noallrightokay/center-point-inbox/releases',
  },
};
JS
fi

cp -r "$src/vendor" "$src/icons" "$src/fonts" "$out/"
cp "$src/manifest.json" "$out/"

# The typefaces travel with the app; it must render correctly with no network.
[ -f "$out/fonts/fonts.css" ] || { echo "no vendored fonts at $src/fonts — run rata-next/scripts/vendor-fonts.mjs" >&2; exit 1; }
cp "$here/ui-src/bridge.js" "$out/bridge.js"
cp "$here/ui-src/bridge.css" "$out/bridge.css"

# Three pages, because the interface navigates between them by name.
#
# This was one page — app.html copied over index.html — and it was wrong in a
# way that only shows on a machine that has never run RATA before: with no
# account yet, app.html sends you to auth.html, and auth.html sends you back to
# app.html afterwards. Neither existed in the bundle, so a first run ended on a
# blank page. Ship the names the interface actually asks for.
cp "$src/app.html" "$out/app.html"
cp "$src/auth.html" "$out/auth.html"

# index.html is the entry point Tauri opens, and it is a signpost rather than a
# third copy of a quarter-megabyte file.
cat > "$out/index.html" <<'HTML'
<!doctype html><meta charset="utf-8"><title>RATA</title>
<meta http-equiv="refresh" content="0;url=app.html">
<script>location.replace('app.html')</script>
HTML

# The hook the bridge attaches to. If this ever disappears from app.html the
# desktop build must fail here rather than ship an app whose every action
# silently does nothing.
grep -q '__RATA_NATIVE__' "$out/app.html" || {
  echo "app.html has no __RATA_NATIVE__ hook in apiFetch — the desktop bridge has nothing to attach to" >&2
  exit 1
}

# Load the bridge before anything else runs.
grep -q '<script src="config.js"></script>' "$out/app.html" || {
  echo "app.html no longer loads config.js — the bridge injection point has moved" >&2
  exit 1
}
# Only app.html gets the bridge. On auth.html it would put a licence box over
# the sign-up form, which is neither the right moment nor the right screen.
python3 - "$out/app.html" <<'PY'
import sys
p = sys.argv[1]
s = open(p, encoding='utf-8').read()
anchor = '<script src="config.js"></script>'
s = s.replace(anchor, anchor + '\n<link rel="stylesheet" href="bridge.css">\n<script src="bridge.js"></script>', 1)

# The fonts used to be stripped here, because a local-first mail app that
# contacts Google on every launch tells Google when its customer opens their
# mail. They are vendored now, so there is nothing to strip — but a page that
# reintroduced a Google link would put that request back into an app that is
# supposed to work with no network at all, and the content security policy would
# block it silently. Fail here instead.
import re
if re.search(r'fonts\.(googleapis|gstatic)\.com', s):
    sys.exit('app.html loads fonts from Google; the desktop build has no network for them '
             '(see rata-next/scripts/vendor-fonts.mjs)')
open(p, 'w', encoding='utf-8').write(s)
PY

echo "ui/ assembled from rata-next/public, $dist build, in $out ($(du -sh "$out" | cut -f1))"
